/* =====================================================================
   Lusitânia Stores — Project 1, Step 4
   Creates the stored procedure that loads dim.Store from stg.Store.

   dim.Store is SCD Type 1:
     - new store in staging        → INSERT a new row (new surrogate key)
     - existing store has changed  → UPDATE the row in place (no history)
     - existing store, no change   → do nothing

   Run this whole file in SSMS (F5). It creates the procedure, runs it
   once, and shows the result. Safe to rerun.
   ===================================================================== */

USE LusitaniaDW;
GO

CREATE OR ALTER PROCEDURE etl.usp_Load_DimStore
AS
BEGIN
    SET NOCOUNT ON;

    -- Collects what MERGE did to each row: 'INSERT' or 'UPDATE'
    DECLARE @Actions TABLE (Action NVARCHAR(10));

    MERGE dim.Store AS tgt                      -- target: the dimension
    USING (
        SELECT StoreCode, StoreName, StoreType, City, District, OpenDate
        FROM stg.Store
    ) AS src                                    -- source: staging
       ON tgt.StoreCode = src.StoreCode         -- match on the BUSINESS key

    -- 1) Store exists AND at least one column is different → overwrite (SCD1)
    --    EXCEPT compares column by column and treats NULL = NULL as equal,
    --    which a plain "<>" comparison does not.
    WHEN MATCHED AND EXISTS (
            SELECT src.StoreName, src.StoreType, src.City, src.District, src.OpenDate
            EXCEPT
            SELECT tgt.StoreName, tgt.StoreType, tgt.City, tgt.District, tgt.OpenDate
         )
    THEN UPDATE SET
            tgt.StoreName = src.StoreName,
            tgt.StoreType = src.StoreType,
            tgt.City      = src.City,
            tgt.District  = src.District,
            tgt.OpenDate  = src.OpenDate,
            tgt.UpdatedAt = SYSDATETIME()

    -- 2) Store not in the dimension yet → insert (StoreSK is generated by IDENTITY)
    WHEN NOT MATCHED BY TARGET
    THEN INSERT (StoreCode, StoreName, StoreType, City, District, OpenDate)
         VALUES (src.StoreCode, src.StoreName, src.StoreType, src.City, src.District, src.OpenDate)

    OUTPUT $action INTO @Actions;

    -- Report what happened (SSIS can read this later for logging)
    SELECT
        RowsInserted = SUM(CASE WHEN Action = 'INSERT' THEN 1 ELSE 0 END),
        RowsUpdated  = SUM(CASE WHEN Action = 'UPDATE' THEN 1 ELSE 0 END)
    FROM @Actions;
END;
GO

/* ---------------------------------------------------------------------
   TEST 1 — first run: all 9 stores are new → expect RowsInserted = 9
   --------------------------------------------------------------------- */
EXEC etl.usp_Load_DimStore;

SELECT StoreSK, StoreCode, StoreName, StoreType, City, InsertedAt, UpdatedAt
FROM dim.Store
ORDER BY StoreSK;
GO

/* ---------------------------------------------------------------------
   TEST 2 — run again with no changes → expect 0 inserted, 0 updated
   (this proves the load is IDEMPOTENT: rerunning it changes nothing)
   --------------------------------------------------------------------- */
EXEC etl.usp_Load_DimStore;
GO

/* ---------------------------------------------------------------------
   TEST 3 — simulate a change: the Braga store is renamed in staging
   → expect 0 inserted, 1 updated, and the SAME StoreSK as before
   --------------------------------------------------------------------- */
UPDATE stg.Store
SET StoreName = N'Lusitânia Braga Parque'
WHERE StoreCode = 'BRG01';

EXEC etl.usp_Load_DimStore;

SELECT StoreSK, StoreCode, StoreName, UpdatedAt
FROM dim.Store
WHERE StoreCode = 'BRG01';

-- Undo the test change in staging (the next SSIS run would overwrite it anyway)
UPDATE stg.Store
SET StoreName = N'Lusitânia Braga'
WHERE StoreCode = 'BRG01';

EXEC etl.usp_Load_DimStore;
GO
